    sys.setrecursionlimit(1 << 20)
    data = sys.stdin.read().split()
    n = int(data[0])
    pre = [int(x) for x in data[1:1 + n]]
    ino = [int(x) for x in data[1 + n:1 + 2 * n]]
    pos = {v: i for i, v in enumerate(ino)}    # ⭐ O(1) 定位根

    post, it, leaves = [], iter(pre), 0

    def build(lo, hi):
        nonlocal leaves
        if lo > hi:
            return 0
        val = next(it); mid = pos[val]
        hl = build(lo, mid - 1)               # ⚠️ 必须先左后右
        hr = build(mid + 1, hi)
        post.append(val)                       # 左右都完了再记 -> 后序
        if hl == 0 and hr == 0:
            leaves += 1
        return 1 + max(hl, hr)

    height = build(0, n - 1)
